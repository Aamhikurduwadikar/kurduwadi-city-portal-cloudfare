-- IMAGE STORAGE/CDN: Supabase Storage serves files through its CDN.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('community-images','community-images',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=true, file_size_limit=5242880, allowed_mime_types=array['image/jpeg','image/png','image/webp'];

drop policy if exists "public read community images" on storage.objects;
create policy "public read community images" on storage.objects for select using (bucket_id='community-images');
drop policy if exists "anon upload community images" on storage.objects;
create policy "anon upload community images" on storage.objects for insert to anon, authenticated with check (bucket_id='community-images');
drop policy if exists "admin delete community images" on storage.objects;
create policy "admin delete community images" on storage.objects for delete to authenticated using (bucket_id='community-images' and public.is_admin());

