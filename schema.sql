-- KURDUWADI CITY PORTAL - SUPABASE DATABASE
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  education text,
  job text,
  city text not null,
  state text default 'Maharashtra',
  country text default 'India',
  blood_group text,
  skills text,
  phone text,
  is_public boolean default false,
  blood_public boolean default false,
  status text default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz default now()
);

create table if not exists public.admin_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'admin',
  created_at timestamptz default now()
);

create table if not exists public.news (
  id bigint generated by default as identity primary key,
  title text not null,
  content text not null,
  category text default 'शहर',
  image_url text,
  author_name text,
  author_phone text,
  source_url text,
  published boolean default false,
  status text default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  title text not null,
  event_date date,
  event_time text,
  location text,
  description text not null,
  organizer text,
  contact text,
  image_url text,
  published boolean default false,
  status text default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz default now()
);

create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text,
  image_url text not null,
  published boolean default true,
  created_at timestamptz default now()
);

-- Safe admin check. Add only trusted auth.users IDs to admin_profiles.
create or replace function public.is_admin()
returns boolean
language sql
security definer
set search_path = public
stable
as $$
  select exists (select 1 from public.admin_profiles where id = auth.uid() and role = 'admin');
$$;

alter table public.profiles enable row level security;
alter table public.admin_profiles enable row level security;
alter table public.news enable row level security;
alter table public.events enable row level security;
alter table public.gallery enable row level security;

-- PROFILES
 drop policy if exists "public approved profiles" on public.profiles;
create policy "public approved profiles" on public.profiles for select using (status='approved' and is_public=true);
drop policy if exists "public profile submissions" on public.profiles;
create policy "public profile submissions" on public.profiles for insert to anon, authenticated with check (status='pending');
drop policy if exists "admin manage profiles" on public.profiles;
create policy "admin manage profiles" on public.profiles for all to authenticated using (public.is_admin()) with check (public.is_admin());

-- NEWS: visitors can submit, but only approved+published news is public.
drop policy if exists "public approved news" on public.news;
create policy "public approved news" on public.news for select using (status='approved' and published=true);
drop policy if exists "public news submissions" on public.news;
create policy "public news submissions" on public.news for insert to anon, authenticated with check (status='pending' and published=false);
drop policy if exists "admin manage news" on public.news;
create policy "admin manage news" on public.news for all to authenticated using (public.is_admin()) with check (public.is_admin());

